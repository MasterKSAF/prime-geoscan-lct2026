export const checkStatusText: Record<Check['status'], string> = {
  pass: 'Пройдено',
  fail: 'Не пройдено',
  unknown: 'Условия модели',
};

export function plainMissionCheck(check: Check) {
  const id = check.id
    .split(':')
    .at(-1)!
    .replace(/^EXPORTED_/, '');
  const quality = id.startsWith('QUALITY_')
    ? Object.keys(qualityCopy)
        .sort((a, b) => b.length - a.length)
        .find((key) => id.endsWith(`_${key}`))
    : undefined;
  const isCoverage =
    ['STRIPS', 'REQUESTED_AREA', 'COVERAGE', 'IMAGE_FOOTPRINTS'].includes(id) ||
    id.startsWith('COVERAGE_') ||
    (id.startsWith('PHOTO_') && id.endsWith('_COVERAGE'));
  const matched = quality
    ? qualityCopy[quality]
    : copy[isCoverage ? 'coverage' : id];
  if (
    check.status === 'fail' &&
    (id.startsWith('UNSUPPORTED_') || id.startsWith('CAMERA_'))
  )
    return {
      title: 'Работу не удалось назначить',
      explanation: check.detail,
    };
  return {
    title: matched?.[0] ?? check.title,
    explanation:
      check.status === 'pass'
        ? 'Условие соблюдено в расчёте.'
        : check.status === 'unknown'
          ? 'Результат ограничен исходными данными. Условия — в подробностях.'
          : (matched?.[1] ??
            `Не пройдена проверка «${check.title}». Причина — в подробностях.`),
  };
}

export function shortMissionVerdict(
  candidate: Pick<MissionCandidate, 'status' | 'checks'>,
) {
  const failed = candidate.checks.filter((c) => c.status === 'fail');
  const ready = candidate.status === 'feasible_model' && failed.length === 0;
  const reasons = [
    ...new Set(failed.map((c) => plainMissionCheck(c).explanation)),
  ];
  return {
    ready,
    title: ready ? 'План готов к симуляции' : 'План нельзя запустить',
    reason: ready
      ? ''
      : reasons.slice(0, 2).join(' ') ||
        (candidate.status === 'unsupported'
          ? 'Выбранные условия пока не поддерживаются. Измените параметры миссии.'
          : 'Полный маршрут не найден. Проверьте доступные БВС, участки и срок.'),
  };
}
