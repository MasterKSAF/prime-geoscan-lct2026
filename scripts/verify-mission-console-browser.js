    const types=['Мультиспектр','Тепловая съёмка','Лазерное сканирование','Геофизика'];
    for(const type of types) await page.getByRole('checkbox',{name:new RegExp('^'+type)}).check();
    check('five work types selected simultaneously',await page.locator('[data-slot=checkbox][aria-checked=true]').count()===5);
    await page.getByRole('button',{name:'2. Территория',exact:true}).click();
    check('each work has separately editable area',await page.getByRole('combobox',{name:'Настройки работы'}).locator('option').count()===5);
    await page.getByRole('button',{name:'1. Работы',exact:true}).click();
    await page.getByRole('textbox',{name:'Название миссии',exact:true}).fill('Проверка пяти видов работ');
    await actions();
    const exported=page.waitForEvent('download');
    await page.getByRole('button',{name:'Скачать задание JSON',exact:true}).click();
    await (await exported).saveAs(`${out}/multi-work.json`);
    await close();
    await tab('Миссии');
    await page.locator('input[type=file][accept=".json,.yaml,.yml"]').setInputFiles(`${out}/multi-work.json`);
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    check('import opens editor first section',await page.getByRole('heading',{name:'Какие работы выполнить?'}).isVisible());
    check('multi-work survives export and reimport',await page.locator('[data-slot=checkbox][aria-checked=true]').count()===5);
    check('loaded mission name editable',await page.getByRole('textbox',{name:'Название миссии',exact:true}).inputValue()==='Проверка пяти видов работ');
    for(const type of types) await page.getByRole('checkbox',{name:new RegExp('^'+type)}).uncheck();
    check('removing types leaves original RGB',await page.locator('[data-slot=checkbox][aria-checked=true]').count()===1);
    await page.getByRole('textbox',{name:'Название миссии',exact:true}).fill(initialName);
    await page.locator('.mw-wizard-body').evaluate(el=>el.scrollTop=0);
    await shot('editor');
    await page.getByRole('button',{name:'Нарисовать область работ',exact:true}).click();
    const box=await page.locator('.mission-map-canvas').boundingBox();
    for(const [x,y] of [[.35,.4],[.6,.4],[.5,.6]]) await page.mouse.click(box.x+box.width*x,box.y+box.height*y);
    check('map remains mounted while drawing',await host.evaluate(el=>el===document.querySelector('.mission-map-canvas')&&el.classList.contains('leaflet-container')));
    await page.keyboard.press('Escape');
    check('escape exits drawing',await page.locator('.mission-map').getAttribute('data-drawing')==='false');
    await page.getByRole('button',{name:'Настройки и справка'}).click();
    await page.getByRole('combobox',{name:'Тема интерфейса'}).selectOption('dark');
    await close();
    await page.waitForFunction(()=>document.documentElement.dataset.primeTheme==='dark');
    check('dark theme remains after settings close',await page.locator('html').getAttribute('data-prime-theme')==='dark');
    await settle();await shot('dark');
    await page.getByRole('button',{name:'Настройки и справка'}).click();
    await page.getByRole('combobox',{name:'Тема интерфейса'}).selectOption('system');
    check('system theme available',await page.getByRole('combobox',{name:'Тема интерфейса'}).inputValue()==='system');
    await page.getByRole('combobox',{name:'Тема интерфейса'}).selectOption('light');
    await page.getByRole('button',{name:'Справка по программе',exact:true}).click();
    check('full help opens from gear',await page.getByRole('dialog',{name:'Справка по программе'}).isVisible());
    await page.getByRole('tab',{name:'Словарь',exact:true}).click();
    check('help explains RGB aliases and battery reserve',await page.getByText('RGB, RGB A, RGB B',{exact:true}).isVisible()&&await page.getByText('Резерв 25% и текущий заряд',{exact:true}).isVisible());
    await close();
    const solving=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();
    const response=await solving; const result=await response.json();
    check('real solver returns HTTP200',response.status()===200);
    check('original RGB still feasible after edit roundtrip',result.candidates.every(c=>c.status==='feasible_model'));
    await page.locator('main[data-planning-step=variants]').waitFor();
    check('variants show map and hide editor',await page.locator('.mw-map-wrap').isVisible()&&!await page.locator('.mw-sidebar').isVisible());
    await shot('variants');
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await page.getByRole('dialog').getByRole('button',{name:/Подтвердить/}).click();
    await page.getByRole('button',{name:'К выполнению',exact:true}).click();
    const controlBox=await page.locator('.mw-playback').boundingBox();
    const mapBox=await page.locator('.mw-map-wrap').boundingBox();
    check('playback above map in first viewport',controlBox.y<mapBox.y&&controlBox.y+controlBox.height<960);
    check('timeline and detailed telemetry collapsed',!await page.locator('.mw-flight-schedule').evaluate(el=>el.open)&&!await page.locator('.mw-telemetry').evaluate(el=>el.open));
    check('execution hides total-duration metric strip',!await page.locator('.mw-metrics').isVisible());
    await page.getByRole('combobox',{name:'Скорость симуляции'}).selectOption('100');
    await page.locator('.mw-playback').getByRole('button',{name:'Начать симуляцию',exact:true}).click();
    await page.locator('.mw-drone-button.moving').first().waitFor({timeout:20000});
    check('running status explicit',await page.locator('.mw-flight-status[data-running=true]').isVisible());
    const marker=page.locator('.mw-drone-marker').first();
    const markerElement=await marker.elementHandle();
    const old=await marker.getAttribute('style');
    await page.waitForFunction(previous=>document.querySelector('.mw-drone-marker')?.getAttribute('style')!==previous,old);
    check('drone marker really moves without remount',await markerElement.evaluate(el=>el.isConnected));
    const markers=await page.locator('.mw-drone-marker').count();
    check('labeled markers match used fleet',markers===new Set(result.candidates[0].sorties.map(s=>s.vehicleId)).size);
    if(markers>1){await page.getByRole('button',{name:'На карте: БВС 02',exact:true}).click();check('map selection selects fleet card',await page.getByRole('button',{name:'Выбрать БВС 02',exact:true}).getAttribute('aria-pressed')==='true');}
    await shot('execution');
    await tab('Миссии');
    check('queue records running simulation',await page.locator('.mo-run').count()===1);
    await tab('Выполнение');
    check('running survives navigation',await page.locator('.mw-flight-status').getAttribute('data-running')==='true');
    check('Leaflet canvas still same',await host.evaluate(el=>el===document.querySelector('.mission-map-canvas')));
    await page.locator('.mw-playback').getByRole('button',{name:'Пауза',exact:true}).click();
    await page.locator('.mw-playback').getByRole('button',{name:'Продолжить симуляцию',exact:true}).waitFor();
    check('paused markers stop indicating flight',await page.locator('.mw-drone-button.moving').count()===0);
    const stopped=await marker.getAttribute('style');await settle();
    check('pause retains position',await marker.getAttribute('style')===stopped);
    await page.setViewportSize({width:390,height:844});await settle();
    check('mobile execution has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    check('mobile execution map remains visible',await page.locator('.mw-map-wrap').isVisible());await shot('mobile-execution');
    await page.setViewportSize({width:1440,height:960});await tab('Результаты');
    check('results own evidence export',await page.locator('.mw-delivery').isVisible());
    const evidence=page.waitForEvent('download');await page.getByRole('button',{name:'Доказательства',exact:true}).click();await (await evidence).saveAs(`${out}/evidence.json`);
    await shot('results');
    await tab('Миссии');await shot('missions-history');
    await tab('Редактор');await page.getByRole('button',{name:'1 Задание',exact:true}).click();
    await page.getByRole('textbox',{name:'Название миссии',exact:true}).fill('Изменённая миссия после проверки');
    check('editing invalidates old approval',!await page.getByRole('button',{name:'План подтверждён',exact:true}).count());
    await actions();await page.getByRole('button',{name:'Сохранить копию…',exact:true}).click();
    await page.getByRole('textbox',{name:'Новый номер / ID миссии'}).fill(`console-${Date.now()}`);
    await page.getByRole('button',{name:'Создать новую миссию',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await tab('Миссии');await page.getByRole('button',{name:'Сохранённые задания',exact:true}).click();
    check('saved copy is listed in library',await page.getByRole('dialog').getByText('Изменённая миссия после проверки · копия',{exact:true}).isVisible());
    await close();
    check('no unhandled browser errors',errors.length===0,errors.join('\n'));
