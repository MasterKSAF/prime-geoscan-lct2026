    await page.setViewportSize({width:1440,height:960});
    await page.goto('http://127.0.0.1:3016/planner');
    await page.getByRole('button',{name:'Редактировать задание',exact:true}).waitFor();
    check('starts on mission overview',await page.locator('main').getAttribute('data-workspace')==='missions');
    check('only four main tabs',await page.getByRole('tab').count()===4);
    check('branding and test toolbar removed',!await page.getByText('MISSION PLANNER',{exact:true}).count()&&!await page.getByRole('button',{name:'Как проверить',exact:true}).count());
    check('theme not exposed in work area',!await page.getByRole('combobox',{name:'Тема интерфейса'}).isVisible());
    await shot('missions');
    await page.getByRole('button',{name:'Создать миссию',exact:true}).click();
