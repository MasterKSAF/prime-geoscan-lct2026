async (page) => {
  const out = 'output/playwright/three-demos', checks = [], errors = [], runs = [];
  const check = (name, pass, detail = '') => { checks.push({name, pass: !!pass, detail}); if (!pass) throw Error(`${name}: ${detail}`); };
  const nav = name => page.getByRole('tablist', {name:'Разделы стенда'}).getByRole('tab', {name, exact:true});
  const resultTab = name => page.getByRole('tablist', {name:'Разделы результатов'}).getByRole('tab', {name, exact:true});
  const home = page.getByRole('region', {name:'Задания и выполнения'});
  const saveDownload = async (name, action) => { const p=page.waitForEvent('download'); await action(); const file=await p; await file.saveAs(`${out}/${name}`); let text=''; const stream=await file.createReadStream(); for await(const chunk of stream) text+=chunk.toString(); return JSON.parse(text); };
  const solve = async () => { const p=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST'); await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click(); const response=await p; check('solve returns HTTP 200',response.status()===200); return response.json(); };
  const openDemo = async n => {
    await nav('Миссии').click();
    await page.getByRole('button',{name:'Готовые примеры',exact:true}).click();
    const card=page.locator(`[data-scenario-id="demo-0${n}-${n===1?'survey':n===2?'obstacles':'repair'}"]`);
    check(`demo ${n}: gallery card and JSON are visible`,await card.isVisible()&&await card.getByRole('link',{name:'JSON',exact:true}).isVisible());
    if(n===1)await page.screenshot({path:`${out}/gallery.png`,fullPage:true});
    await card.getByText('Показать по шагам',{exact:true}).click();
    check(`demo ${n}: five demonstration steps`,await card.locator('ol li').count()===5);
    await card.getByRole('button',{name:`Открыть демо ${n}`,exact:true}).click();
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    check(`demo ${n}: preview enters editor without launching`,await nav('Редактор').getAttribute('aria-selected')==='true');
  };
  const complete = async (label, result) => {
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await page.getByRole('dialog').getByRole('button',{name:/Подтвердить/}).click();
    await page.getByRole('button',{name:'К выполнению',exact:true}).click();
    await page.waitForFunction(()=>{const tiles=Array.from(document.querySelectorAll('.leaflet-tile')).filter(tile=>tile.getBoundingClientRect().width>0);return tiles.length>0&&tiles.every(tile=>tile.complete&&tile.naturalWidth>0)},null,{timeout:20000});
    await page.getByRole('combobox',{name:'Скорость симуляции',exact:true}).selectOption('300');
    await page.getByRole('button',{name:'Начать симуляцию',exact:true}).click();
    await page.getByRole('region',{name:'Модельная симуляция'}).getByText('Идёт симуляция',{exact:true}).waitFor({timeout:20000});
    const firstSurvey=Math.min(...result.candidates[0].sorties.flatMap(s=>s.segments.filter(p=>p.phase==='survey').map(p=>p.startSec)));
    await page.waitForFunction(target=>Number(document.querySelector('input[aria-label="Время симуляции"]')?.value)>target,firstSurvey+30,{timeout:20000});
    check(`${label}: simulation starts`,await page.locator('.mw-map-wrap').isVisible());
    await page.screenshot({path:`${out}/${label}-flight.png`});
    await page.getByRole('region',{name:'Модельная симуляция'}).getByText('Миссия завершена',{exact:true}).waitFor({timeout:60000});
    check(`${label}: simulation reaches completion`,await page.locator('.mw-playback-time').isVisible());
    await nav('Миссии').click();
    await home.getByRole('tab',{name:/^История/}).click();
    const row=home.getByRole('article',{name:`Выполнение ${result.document.name}`,exact:true});
    check(`${label}: history retains completed run`,await row.locator('.mo-completed').isVisible());
    await row.getByRole('button',{name:'Открыть выполнение',exact:true}).click();
    await nav('Результаты').click();
    if(label!=='demo-03-fixed') {
      await resultTab('Анализ').click();
      const retreat=page.locator('details[aria-label="Предполётная проверка ухода"]');
      await retreat.locator('summary').first().click();
      const response=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/contingency')&&r.request().method()==='POST');
      await retreat.getByRole('button',{name:'Проверить уход по всему маршруту',exact:true}).click();
      const report=await (await response).json();
      check(`${label}: continuous return certificate verified in model`,report.status==='certified_model'&&report.checkedAnchors===report.anchorCount,JSON.stringify({status:report.status,reasons:report.reasons}));
      await saveDownload(`${label}.contingency.json`,()=>retreat.getByRole('button',{name:'Отчёт ухода JSON',exact:true}).click());
      await resultTab('Итог').click();
    }
    await resultTab('Итог').click();
    const data=page.getByRole('region',{name:'Данные и батареи после миссии'});
    check(`${label}: data handover does not claim imagery`,(await data.innerText()).includes('Реальные файлы не получены')&&(await data.innerText()).includes('После симуляции'));
    await data.getByText('Расчётные остатки батарей',{exact:true}).click();
    await data.getByRole('button',{name:'Пояснение: Как читать остатки батарей',exact:true}).hover();
    const batteryHelp=page.getByRole('tooltip').filter({hasText:'Как читать остатки батарей'});
    check(`${label}: batteries are shown as model estimates`,await batteryHelp.isVisible()&&(await batteryHelp.innerText()).includes('не свежая телеметрия'));
    await data.getByRole('button',{name:'Пояснение: Как читать остатки батарей',exact:true}).press('Escape');
    const manifest=await saveDownload(`${label}.delivery-manifest.json`,()=>data.getByRole('button',{name:'Манифест JSON',exact:true}).click());
    check(`${label}: downloaded manifest retains real-data boundary and source hash`,manifest.inputHash===result.inputHash&&manifest.phase==='simulation-completed'&&manifest.receivedData===false&&manifest.transferPerformed===false&&manifest.receivedFiles.length===0&&manifest.flightReady===false);
    const evidence=await saveDownload(`${label}.evidence.json`,()=>page.getByRole('button',{name:'Скачать комплект JSON',exact:true}).click());
    check(`${label}: downloaded evidence is bound to this model plan`,evidence.inputHash===result.inputHash&&evidence.planHash===manifest.planHash&&evidence.flightReady===false&&evidence.candidate.status==='feasible_model');
    await page.screenshot({path:`${out}/${label}-result.png`,fullPage:true});
    runs.push({label,missionId:result.document.id,inputHash:result.inputHash,status:'simulation-completed'});
  };
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>void d.accept().catch(()=>{}));
  try {
    await page.setViewportSize({width:1440,height:960});
    await openDemo(1);
    const editor=page.locator('.mw-simple-editor');
    await editor.getByLabel('Название миссии',{exact:true}).fill('Демо 1 · Проверенный показ');
    await page.getByRole('button',{name:'Сохранить',exact:true}).click();
    await nav('Миссии').click();
    await home.getByRole('tab',{name:/^Задания/}).click();
    check('demo 1: edited task is saved before launch',await home.getByRole('button',{name:'Открыть задание',exact:true}).count()===1);
    await home.getByRole('button',{name:'Открыть задание',exact:true}).click();
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    await editor.getByRole('button',{name:'Парк',exact:true}).click();
    check('demo 1: fleet editing remains accessible',await editor.getByText('Добавить БВС · Gemini, 801, 201 / изменить парк',{exact:true}).isVisible());
    await editor.getByRole('button',{name:'Задание',exact:true}).click();
    const first=await solve();
    check('demo 1: complete plan for the original square',first.candidates.every(c=>c.status==='feasible_model'&&c.metrics.grossCoveragePct>=99.99));
    check('demo 1: fastest choice uses at least two aircraft',first.candidates[0].metrics.vehicleCount>=2);
    await page.locator('.mw-plan-select').filter({has:page.getByRole('heading',{name:'Раньше завершить',exact:true})}).click();
    await complete('demo-01',first);

    await openDemo(2);
    await editor.getByRole('button',{name:'Условия',exact:true}).click();
    check('demo 2: restrictions are in the editable conditions',await editor.locator('summary').filter({hasText:/Препятствия|Ограничения|Запреты/}).count()>0);
    await editor.getByRole('button',{name:'Задание',exact:true}).click();
    const second=await solve();
    check('demo 2: high obstacle remains in input',second.document.restrictions[0].maxAltitudeM===160);
    check('demo 2: both jobs covered by two separated aircraft',second.candidates.every(c=>c.status==='feasible_model'&&c.metrics.grossCoveragePct>=99.99&&c.metrics.vehicleCount===2&&c.sorties[0].startSec!==c.sorties[1].startSec));
    await complete('demo-02',second);

    // Use the downloadable file for the third story, not a hidden fixture injection.
    await nav('Миссии').click();
    await page.locator('input[type=file][accept=".json,.yaml,.yml"]').setInputFiles('public/planner/scenarios/demo-03-repair.mission.json');
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    const third=await solve();
    check('demo 3: low charge produces rejected plans',third.candidates.every(c=>c.status!=='feasible_model'));
    check('demo 3: rejected plan cannot be approved',!(await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).isEnabled()));
    await nav('Результаты').click(); await resultTab('Анализ').click();
    const panel=page.getByRole('region',{name:'Анализ решения'});
    const repair=panel.locator('article').filter({has:page.getByRole('heading',{name:'Заменить батарею: БВС 07 · фотокамера PF1B',exact:true})});
    check('demo 3: named battery repair is visible without expansion',await repair.getByRole('button',{name:'Проверить вариант',exact:true}).isVisible());
    await page.screenshot({path:`${out}/demo-03-rejected.png`,fullPage:true});
    const pending=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await repair.getByRole('button',{name:'Проверить вариант',exact:true}).click();
    const alternative=await (await pending).json();
    check('demo 3: battery hypothesis reruns the real solver',alternative.candidates.every(c=>c.status==='feasible_model')&&alternative.document.scenario.vehicles[0].batteryPct===100&&third.document.scenario.vehicles[0].batteryPct===26);
    await repair.getByRole('button',{name:'Открыть копию задания',exact:true}).waitFor();
    check('demo 3: physical hypothesis needs acknowledgement',!(await repair.getByRole('button',{name:'Открыть копию задания',exact:true}).isEnabled()));
    await saveDownload('demo-03-repair-comparison.json',()=>repair.getByRole('button',{name:'Скачать сравнение',exact:true}).click());
    await repair.getByRole('checkbox',{name:/Понимаю: это гипотеза/}).check();
    await repair.getByRole('button',{name:'Открыть копию задания',exact:true}).click();
    check('demo 3: revised task still goes through preview',await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).isVisible());
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    const fixed=await solve();
    check('demo 3: fixed task is a separate new ID',fixed.document.id!==third.document.id&&fixed.candidates.every(c=>c.status==='feasible_model'));
    await complete('demo-03-fixed',fixed);
    check('no unhandled browser errors',errors.length===0,errors.join('\n'));
  } catch(e) { checks.push({name:'fatal',pass:false,detail:String(e)}); await page.screenshot({path:`${out}/failure.png`,fullPage:true}); }
  const report={at:new Date().toISOString(),modelOnly:true,checks,errors,runs,status:checks.every(c=>c.pass)?'pass':'fail'};
  await saveDownload('browser-report.json',()=>page.evaluate(value=>{const url=URL.createObjectURL(new Blob([JSON.stringify(value,null,2)],{type:'application/json'}));const a=document.createElement('a');a.href=url;a.download='browser-report.json';a.click();setTimeout(()=>URL.revokeObjectURL(url),1000)},report));
  return report;
}
