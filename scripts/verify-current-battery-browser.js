async (page) => {
  const checks=[], errors=[]; const out='output/playwright/current-battery';
  const check=(name,pass,detail='')=>{checks.push({name,pass:!!pass,detail});if(!pass)throw Error(name+': '+detail);};
  page.on('pageerror',e=>errors.push(e.message));
  page.removeAllListeners('dialog');page.on('dialog',d=>void d.accept().catch(()=>{}));
  const close=async()=>page.getByRole('dialog').getByRole('button',{name:'Закрыть окно',exact:true}).click();
  const panel=()=>page.getByRole('dialog',{name:'Состояние парка',exact:true});
  const fleet=async()=>{await panel().getByText('Формат файла и журнал',{exact:true}).click();return JSON.parse(await panel().locator('pre').innerText());};
  const shot=async name=>page.screenshot({path:`${out}/${name}.png`,animations:'disabled'});
  try {
    await page.setViewportSize({width:1440,height:960});
    check('fleet entry on first screen',await page.getByRole('button',{name:'Парк',exact:true}).isVisible());
    await page.locator('input[type=file][accept=".json,.yaml,.yml"]').setInputFiles('public/planner/scenarios/repeat-sorties.mission.json');
    await page.getByRole('button',{name:'Заменить текущее задание',exact:true}).click();
    await page.locator('.mission-map[data-map-ready=true]').waitFor();
    const host=await page.locator('.mission-map-canvas').elementHandle();
    await page.getByRole('button',{name:'4. Парк БВС',exact:true}).click();
    check('current charge editable',await page.getByRole('spinbutton',{name:'Текущий заряд, %',exact:true}).isVisible());
    check('no spare inventory or charge duration fields',!await page.getByText('Батарей:',{exact:true}).count()&&!await page.getByRole('spinbutton',{name:'Полная зарядка, мин',exact:true}).count());
    await page.getByRole('spinbutton',{name:'Текущий заряд, %',exact:true}).fill('72');
    let solving=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();
    const response=await solving, result=await response.json();
    check('server 200',response.status()===200,JSON.stringify(result.error));
    check('three sorties at 72 percent',result.candidates[0].status==='feasible_model'&&result.candidates[0].sorties.length===3&&result.document.batteries[0].initialPct===72);
    check('all sorties use same battery',new Set(result.candidates[0].sorties.map(s=>s.batteryId)).size===1&&result.candidates[0].metrics.batteryChanges===0);
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await page.getByRole('dialog').getByRole('button',{name:/Подтвердить/}).click();
    await page.getByRole('button',{name:'К выполнению',exact:true}).click();
    await page.getByRole('combobox',{name:'Скорость симуляции'}).selectOption('100');
    await page.locator('.mw-playback').getByRole('button',{name:'Начать симуляцию',exact:true}).click();
    await page.locator('.mw-drone-button.moving').first().waitFor({timeout:20000});
    check('simulation visibly moves UAV',await page.locator('.mw-flight-status[data-running=true]').isVisible());await shot('execution');
    await page.locator('.mw-flight-status[data-running=false]').waitFor({timeout:45000});
    await page.getByRole('button',{name:'Парк',exact:true}).click();
    let states=await fleet();
    check('landed SOC persisted below initial value',states.length===1&&states[0].grounded&&states[0].ready&&states[0].battery.initialPct<72&&states[0].battery.initialPct>=25,JSON.stringify(states));
    await shot('remaining-charge');
    await panel().getByRole('spinbutton',{name:'Текущий заряд, %',exact:true}).fill('100');
    await panel().getByRole('button',{name:'Записать состояние',exact:true}).click();
    await panel().getByRole('alert').waitFor();
    check('SOC increase without replacement refused',(await panel().getByRole('alert').innerText()).includes('замены'));
    await panel().getByRole('checkbox',{name:'Батарея заменена',exact:true}).check();
    await panel().getByRole('button',{name:'Записать состояние',exact:true}).click();
    await page.waitForFunction(()=>{const p=document.querySelector('.mw-fleet-state-panel pre');return p&&JSON.parse(p.textContent)[0].battery.initialPct===100;});
    states=JSON.parse(await panel().locator('pre').innerText());
    check('explicit replacement saved, no mission auto-start',states[0].replacements.length===1&&!await page.locator('.mw-flight-status[data-running=true]').count());
    await panel().locator('input[type=file]').setInputFiles('output/playwright/current-battery/joined-state.json');
    await panel().getByRole('button',{name:'Подтвердить состояние из файла',exact:true}).click();
    await panel().getByRole('button',{name:/Новый БВС/}).waitFor();
    check('new vehicle registered by report',JSON.parse(await panel().locator('pre').innerText()).length===2);
    await shot('fleet-updated');
    await close();await page.reload();await page.getByRole('button',{name:'Парк',exact:true}).click();
    states=await fleet();check('fleet survives reload',states.length===2&&states.some(s=>s.replacements.length===1));
    await panel().getByRole('button',{name:'Применить парк к заданию',exact:true}).click();
    await page.locator('main[data-workspace=planning]').waitFor();
    check('application opens editable draft',await page.locator('main[data-workspace=planning]').isVisible());
    const pending=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();
    const next=await (await pending).json();
    check('new UAV considered by next calculation',next.document.scenario.vehicles.some(v=>v.id==='joined-browser')&&next.document.fleetSnapshot.length===2);
    check('map survives mission changes',await page.locator('.mission-map-canvas').isVisible());
    await page.setViewportSize({width:390,height:844});
    check('mobile no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await shot('mobile');check('no browser errors',errors.length===0,errors.join('\n'));
  } catch(e) {checks.push({name:'fatal',pass:false,detail:String(e)});await shot('failure');}
  const report={at:new Date().toISOString(),checks,errors};page.__batteryReport=report;return report;
}
