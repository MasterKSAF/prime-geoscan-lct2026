async (page) => {
  const out='output/playwright/tabs-weather-2026-09-19', checks=[], errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>void d.accept());
  const check=(name,pass,detail='')=>{checks.push({name,pass:!!pass,detail});if(!pass)throw new Error(name+': '+detail);};
  const tab=async(name)=>{await page.getByRole('tab',{name,exact:true}).click();await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));};
  const screenshot=async(name)=>page.screenshot({path:`${out}/${name}.png`,fullPage:false});
  let liveForecast=null;
  try {
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:3016/planner');
    await page.locator('.mission-map[data-map-ready=true]').waitFor();
    const map=await page.locator('.mission-map-canvas').elementHandle();
    check('four named workspaces',await page.getByRole('tab').count()===4);
    check('task view hides candidate inspector',!await page.locator('.mw-inspector').isVisible());
    check('task view hides simulation/export',!await page.locator('.mw-playback').isVisible()&&!await page.locator('.mw-delivery').isVisible());
    await screenshot('planning');
    for(const name of ['Миссии','Выполнение','Результаты','Планирование']) {
      await tab(name);
      check(`workspace ${name}`,await page.getByRole('tabpanel',{name,exact:true}).isVisible());
    }
    check('same Leaflet host after tab navigation',await map.evaluate(el=>el===document.querySelector('.mission-map-canvas')));
    check('map visible on return',await page.locator('.mission-map-canvas').isVisible());
    await page.getByRole('button',{name:'Нарисовать область работ',exact:true}).click();
    const box=await page.locator('.mission-map-canvas').boundingBox();
    await page.mouse.click(box.x+box.width*.4,box.y+box.height*.4);
    await page.mouse.click(box.x+box.width*.6,box.y+box.height*.4);
    await page.mouse.click(box.x+box.width*.5,box.y+box.height*.6);
    check('drawing leaves map visible',await page.locator('.mission-map[data-drawing=true]').isVisible());
    await page.keyboard.press('Escape');
    check('escape cancels drawing without replacing map',await map.evaluate(el=>el===document.querySelector('.mission-map-canvas')));
    const calculate=async()=>{
      const response=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
      await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();
      const r=await response;check('real solver HTTP200',r.status()===200);
      const result=await r.json();await page.locator('main[data-planning-step=variants]').waitFor();return result;
    };
    const result=await calculate();
    check('legacy demo still feasible',result.candidates.every(c=>c.status==='feasible_model'));
    check('variants hide task wizard',!await page.locator('.mw-sidebar').isVisible());
    check('variants retain map',await page.locator('.mission-map-canvas').isVisible());
    await screenshot('variants');
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    const approval=page.getByRole('dialog');
    await approval.getByRole('checkbox').check();
    await approval.getByRole('button',{name:/Подтвердить/}).click();
    await page.getByRole('button',{name:'К выполнению',exact:true}).click();
    check('execution controls visible',await page.locator('.mw-playback').isVisible());
    await page.locator('.mw-playback select').selectOption('1');
    await page.getByRole('button',{name:'Начать симуляцию',exact:true}).click();
    await page.getByRole('button',{name:'Пауза',exact:true}).waitFor();
    await tab('Миссии');
    check('mission board visible',await page.locator('.mw-missions-home').isVisible());
    check('map hidden only on non-map workspace',!await page.locator('.mw-map-wrap').isVisible());
    await screenshot('missions');
    // The execution label includes a live badge while running.
    await page.getByRole('tab',{name:/^Выполнение/}).click();
    check('simulation survives navigation',await page.getByRole('button',{name:'Пауза',exact:true}).isVisible());
    await screenshot('execution');
    await page.getByRole('button',{name:'Пауза',exact:true}).click();
    await page.getByRole('button',{name:'Начать симуляцию',exact:true}).waitFor();
    await tab('Результаты');
    check('results own export controls',await page.locator('.mw-delivery').isVisible());
    check('results hide playback/map',!await page.locator('.mw-playback').isVisible()&&!await page.locator('.mw-map-wrap').isVisible());
    const download=page.waitForEvent('download');await page.getByRole('button',{name:'Доказательства',exact:true}).click();
    const file=await download;await file.saveAs(`${out}/manual-evidence.json`);check('evidence export',!await file.failure());
    await screenshot('results');
    await tab('Планирование');
    await page.getByRole('button',{name:'Погода и условия',exact:true}).click();
    const weather=page.getByRole('dialog',{name:'Погода для территории миссии'});
    const weatherResponse=page.waitForResponse(r=>r.url().includes('/api/planner/weather?q='));
    await weather.getByRole('button',{name:'Обновить прогноз',exact:true}).click();
    const response=await weatherResponse;liveForecast=await response.json();
    check('live weather provider HTTP200',response.status()===200,JSON.stringify(liveForecast).slice(0,500));
    check('live forecast five points and complete window',liveForecast.points.length===5&&liveForecast.hours.length===9);
    check('forecast explicitly not telemetry',await weather.getByText(/Это не измерения на борту/).isVisible());
    await screenshot('weather-live');
    await weather.getByRole('button',{name:'Применить к заданию',exact:true}).click();
    check('applying weather returns to task',await page.locator('main[data-planning-step=task]').isVisible());
    const forecastResult=await calculate();
    check('forecast saved in solver input',forecastResult.document.weather.snapshot.provider==='Open-Meteo');
    check('weather checks included',forecastResult.candidates.every(c=>c.checks.some(x=>x.id==='FORECAST_SCOPE')));
    const hasWeatherFailure=forecastResult.candidates.some(c=>c.checks.some(x=>x.id.startsWith('FORECAST_')&&x.status==='fail'));
    check('weather violations block confirmation',!hasWeatherFailure||forecastResult.candidates.every(c=>c.status!=='feasible_model'));
    check('old approval invalidated',!await page.getByRole('button',{name:'План подтверждён',exact:true}).count());
    await tab('Результаты');
    const taskDownload=page.waitForEvent('download');await page.getByRole('button',{name:'JSON',exact:true}).click();
    await (await taskDownload).saveAs(`${out}/live-weather-mission.json`);
    const eDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Доказательства',exact:true}).click();
    await (await eDownload).saveAs(`${out}/live-weather-evidence.json`);
    await tab('Планирование');
    await page.getByRole('button',{name:'Погода и условия',exact:true}).click();
    await page.context().setOffline(true);
    await weather.getByRole('button',{name:'Обновить прогноз',exact:true}).click();
    await weather.getByRole('alert').waitFor();
    check('offline forecast exposes error and retains applied data',await weather.getByRole('button',{name:'Применить к заданию'}).isEnabled());
    await page.context().setOffline(false);
    await weather.getByRole('button',{name:'Закрыть погоду'}).click();
    await page.getByRole('button',{name:'1 Задание',exact:true}).click();
    await page.getByRole('button',{name:'3. Срок',exact:true}).click();
    const inputs=page.locator('.mw-wizard-body input');
    const original=await inputs.first().inputValue();
    await inputs.first().fill('');
    check('empty date does not crash app',await page.getByRole('tab',{name:'Планирование',exact:true}).isVisible());
    await inputs.first().fill(original);
    const timezone=page.getByRole('textbox',{name:/Часовой пояс/});
    const tz=await timezone.inputValue();await timezone.fill('Europe/Mosco');
    check('invalid timezone does not crash app',await page.getByRole('tab',{name:'Планирование',exact:true}).isVisible());
    await timezone.fill(tz);
    await page.getByRole('combobox',{name:'Тема интерфейса'}).selectOption('dark');
    check('dark theme',await page.locator('html').getAttribute('data-prime-theme')==='dark');await screenshot('dark');
    await page.setViewportSize({width:390,height:844});
    check('mobile no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    check('mobile map visible',await page.locator('.mission-map-canvas').isVisible());await screenshot('mobile');
    await page.getByRole('combobox',{name:'Тема интерфейса'}).selectOption('light');
    await page.setViewportSize({width:1440,height:1000});
    check('no unhandled browser exceptions',errors.length===0,errors.join('\n'));
  } catch(e) {checks.push({name:'fatal',pass:false,detail:String(e)});await screenshot('failure');}
  const report={createdAt:new Date().toISOString(),checks,errors,liveForecast};
  page.__workspaceWeatherReport=report;
  return report;
}
