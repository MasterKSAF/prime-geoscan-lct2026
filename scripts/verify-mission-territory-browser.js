async (page) => {
  const out = 'output/playwright/territory-2026-09-20', checks = [], errors = [];
  const check = (name, pass, detail = '') => { checks.push({ name, pass: !!pass, detail }); if (!pass) throw Error(name + ': ' + detail); };
  page.removeAllListeners('dialog'); page.on('dialog', d => void d.accept().catch(() => {}));
  page.on('pageerror', e => errors.push(e.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const tab = async name => page.getByRole('tab', { name, exact: true }).click();
  const settle = async () => page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))));
  const closeToast = async () => { if (await button('Закрыть уведомление').isVisible()) await button('Закрыть уведомление').click(); };
  const shot = async name => { await page.evaluate(() => window.scrollTo(0, 0)); await settle(); await page.screenshot({ path: `${out}/${name}.png`, animations: 'disabled' }); };
  const exportMission = async name => {
    await button('Действия с этой миссией').click();
    const waiting = page.waitForEvent('download'); await button('Скачать задание JSON').click();
    const download = await waiting; await download.saveAs(`${out}/${name}.json`);
    const stream = await download.createReadStream(); let text = ''; for await (const chunk of stream) text += chunk.toString('utf8');
    await page.getByRole('dialog').getByRole('button', { name: 'Закрыть окно', exact: true }).click();
    return JSON.parse(text);
  };
  const stroke = async (kind, positions) => {
    await button(kind).click(); await page.locator('.mission-drawing-surface').waitFor();
    const b = await page.locator('.mission-map').boundingBox();
    const points = positions.map(([x,y]) => [b.x + b.width*x, b.y + b.height*y]);
    await page.mouse.move(...points[0]); await page.mouse.down();
    for (const p of points.slice(1)) await page.mouse.move(...p, { steps: 2 });
    await page.mouse.up(); await page.locator('.mission-drawing-surface').waitFor({ state: 'hidden' }); await settle();
  };
  try {
    await page.setViewportSize({ width: 1440, height: 960 });
    await tab('Миссии'); await button('Создать миссию').click();
    await page.locator('.mission-map[data-map-ready=true]').waitFor();
    await button('2. Территория').click();
    const host = await page.locator('.mission-map-canvas').elementHandle();
    const baseline = await exportMission('baseline');
    const map = await page.locator('.mw-map-wrap').boundingBox(), header = await page.locator('.mw-header-actions').boundingBox();
    check('map and editor begin at top of desktop workspace', map.y < 160, JSON.stringify(map));
    check('mission actions share top navigation row', header.y < 60);
    check('default polygon has draggable vertices', await page.locator('.mission-area-vertex').count() === 4);
    await stroke('Круг', [[.4,.3],[.6,.53]]);
    const circle = await exportMission('circle');
    check('circle creates closed 48-vertex polygon', circle.jobs[0].area.coordinates[0].length === 49 && JSON.stringify(circle.jobs[0].area.coordinates[0][0]) === JSON.stringify(circle.jobs[0].area.coordinates[0].at(-1)));
    await closeToast(); await shot('circle');
    await stroke('Овал', [[.3,.35],[.65,.49]]);
    check('ellipse creates editable bounded polygon', await page.locator('.mission-area-vertex').count() === 48);
    const vertex = page.locator('.mission-area-vertex').first(), before = await vertex.boundingBox();
    await page.mouse.move(before.x+7,before.y+7); await page.mouse.down(); await page.mouse.move(before.x+22,before.y+4,{steps:8}); await page.mouse.up(); await settle();
    check('vertex movement accepted and feedback shown', await page.locator('.mw-toast').innerText().then(t => t.includes('Граница участка изменена')));
    await closeToast();
    await stroke('От руки', [[.3,.35],[.6,.35],[.6,.55],[.4,.55],[.4,.30],[.36,.27]]);
    const free = await exportMission('freehand');
    check('freehand crossing trims tails into a closed polygon', free.jobs[0].area.coordinates[0].length >= 4 && free.jobs[0].area.coordinates[0].length <= 70);
    check('Leaflet canvas survives all drawing and editing', await host.evaluate(el => el === document.querySelector('.mission-map-canvas')));
    await button('Удалить участок').click();
    check('last-area removal clears visible editing vertices and disables solve', await page.locator('.mission-area-vertex').count() === 0 && await button('Рассчитать варианты').isDisabled());
    await button('Сохранить').click();
    check('empty area cannot be saved as a ready mission', (await page.locator('.mw-alert.error').allTextContents()).some(t=>t.includes('Территория удалена')));
    await tab('Миссии'); await tab('Редактор');
    check('empty territory remains required after editor remount', await page.locator('.mt-empty-area').isVisible() && await button('1. Работы').isDisabled());
    await button('Восстановить контур').click(); await button('2. Территория').click();
    check('explicit restore recovers area and enables solve', await button('Рассчитать варианты').isEnabled());
    await button('Добавить участок').click(); await button('Отмена').click();
    check('new area is unassigned until actually drawn', await page.locator('.mt-area-item').count() === 2 && await button('Рассчитать варианты').isDisabled());
    await page.locator('.mt-area-item').first().click();
    await stroke('Овал', [[.4,.35],[.6,.5]]);
    check('editing another area cannot revive the empty area', await button('Рассчитать варианты').isDisabled());
    await page.locator('.mt-area-item').nth(1).click();
    await stroke('Круг', [[.45,.35],[.58,.5]]);
    check('second drawn area clears only its own incomplete state', await button('Рассчитать варианты').isEnabled());
    await page.getByRole('textbox',{name:'Название участка',exact:true}).fill('Второй участок');
    await button('Сохранить').click();
    check('save creates fixed dismissable notification', await page.locator('.mw-toast').evaluate(el => getComputedStyle(el).position === 'fixed'));
    await tab('Результаты');
    check('editor notifications never appear on results', !await page.locator('.mw-toast').isVisible());
    await tab('Редактор'); await button('2. Территория').click(); await closeToast();
    check('notification can be closed explicitly', !await page.locator('.mw-toast').isVisible());
    const multiple = await exportMission('two-areas');
    check('both independent areas survive JSON export', multiple.jobs.length === 2 && multiple.jobs[1].name === 'Второй участок' && JSON.stringify(multiple.jobs[0].area) !== JSON.stringify(multiple.jobs[1].area));
    await button('Удалить участок').click();
    check('delete selected area preserves another', await page.locator('.mt-area-item').count() === 1);
    await button('От руки').click(); await page.keyboard.press('Escape');
    check('Escape releases drawing surface and keeps map', !await page.locator('.mission-drawing-surface').count() && await host.evaluate(el=>el.isConnected));
    await closeToast(); await shot('editor-final');
    await page.setViewportSize({width:390,height:844}); await settle();
    check('mobile has no horizontal overflow', await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1));
    await shot('mobile-editor');
    await page.setViewportSize({width:1440,height:960});
    await page.locator('input[type=file][accept=".json,.yaml,.yml"]').setInputFiles(`${out}/baseline.json`);
    await button('Заменить текущее задание').click();
    const responseWait = page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await button('Рассчитать варианты').click(); const response = await responseWait; const result = await response.json();
    check('real calculation still produces feasible plans', response.status()===200&&result.candidates.every(c=>c.status==='feasible_model'));
    await button('Проверить и подтвердить').click();
    await page.getByRole('dialog').getByRole('checkbox').check(); await page.getByRole('dialog').getByRole('button',{name:/Подтвердить/}).click();
    await button('К выполнению').click(); await closeToast();
    const executionMap = await page.locator('.mw-map-wrap').boundingBox();
    check('execution map visible without scrolling', executionMap.y < 220, JSON.stringify(executionMap));
    await page.getByRole('combobox',{name:'Скорость симуляции'}).selectOption('100');
    await page.locator('.mw-playback').getByRole('button',{name:'Начать симуляцию',exact:true}).click();
    await page.locator('.mw-drone-button.moving').first().waitFor({timeout:30000});
    await closeToast(); await shot('execution');
    check('simulation visibly moves above fold', await page.locator('.mw-drone-button.moving').count()>0 && (await page.locator('.mw-map-wrap').boundingBox()).y < 220);
    check('schedule and incident controls are inside sidebar', await page.locator('.mw-sidebar .mw-safety-console').isVisible() && await page.locator('.mw-sidebar .mw-flight-schedule').isVisible());
    await page.locator('.mw-playback').getByRole('button',{name:'Пауза',exact:true}).click();
    await tab('Результаты'); await shot('results');
    check('results width is bounded', (await page.locator('.mw-results-checks').boundingBox()).width <= 1100);
    check('no unhandled browser errors', errors.length===0, errors.join('\n'));
    check('baseline task unchanged by geometry trials', baseline.jobs.length===1);
  } catch(e) { checks.push({name:'fatal',pass:false,detail:String(e)}); await shot('failure'); }
  const report={createdAt:new Date().toISOString(),url:page.url(),checks,errors}; page.__territoryReport=report; return report;
}
