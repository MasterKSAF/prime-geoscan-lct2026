async (page) => {
  const out='output/playwright/dispatcher',checks=[],errors=[];
  const check=(name,pass,detail='')=>{checks.push({name,pass:!!pass,detail});if(!pass)throw Error(name+': '+detail);};
  const nav=name=>page.getByRole('tablist',{name:'Разделы стенда'}).getByRole('tab',{name,exact:true});
  const save=async(name,action)=>{const p=page.waitForEvent('download');await action();const d=await p;await d.saveAs(`${out}/${name}`);let raw='';for await(const c of await d.createReadStream())raw+=c.toString();return raw;};
  const readRuns=()=>page.evaluate(async()=>new Promise((resolve,reject)=>{const r=indexedDB.open('prime-planner-operations',2);r.onsuccess=()=>{const db=r.result,tx=db.transaction('operations'),q=tx.objectStore('operations').getAll();q.onsuccess=()=>resolve(q.result);tx.oncomplete=()=>db.close();tx.onerror=()=>reject(tx.error);};r.onerror=()=>reject(r.error);}));
  page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>void d.accept());
  try{
    await page.setViewportSize({width:1440,height:960});
    await nav('Парк БВС').click();
    const fleet=page.getByRole('region',{name:'Общий парк БВС',exact:true});
    if(await fleet.getByRole('button',{name:'Загрузить парк JSON',exact:true}).isVisible()){
      await fleet.locator('input[type=file]').setInputFiles('public/planner/scenarios/demo-01-survey.fleet.json');
      await fleet.getByRole('button',{name:'Сохранить парк',exact:true}).click();
      await fleet.getByRole('button',{name:'Сохранить парк',exact:true}).waitFor({state:'hidden'});
    }
    const config=fleet.locator('details').filter({has:page.locator('summary',{hasText:'Добавить / импортировать БВС и изменить комплектации'})});
    if(await config.getAttribute('open')===null)await config.locator('summary').first().click();
    for(const model of ['Gemini','801','201'])await fleet.getByRole('button',{name:`Добавить Геоскан ${model}`,exact:true}).click();
    check('all TZ models can be added',await fleet.locator('.fw-roster article').count()===6);
    await nav('Миссии').click();await nav('Парк БВС').click();
    check('unsaved fleet survives workspace switching',await fleet.locator('.fw-roster article').count()===6);
    await fleet.getByRole('button',{name:'Сохранить парк',exact:true}).click();
    await fleet.getByRole('button',{name:'Сохранить парк',exact:true}).waitFor({state:'hidden'});
    await page.reload();await nav('Парк БВС').click();await fleet.locator('.fw-roster article').nth(5).waitFor();
    check('shared fleet survives reload',await fleet.locator('.fw-roster article').count()===6);
    check('profiles are not presented as real telemetry',(await fleet.innerText()).includes('Не опрошен'));
    await page.screenshot({path:`${out}/01-fleet.png`});
    await nav('Редактор').click();
    const editor=page.locator('.me-editor');
    await editor.getByRole('textbox',{name:'Название миссии',exact:true}).fill('QA · разные работы');
    await editor.getByRole('checkbox',{name:'Тепловая съёмка',exact:true}).check();
    check('multiple types coexist',await editor.getByRole('checkbox',{name:'Фотосъёмка',exact:true}).isChecked());
    await editor.getByRole('button',{name:'Параметры',exact:true}).click();
    await editor.getByRole('spinbutton',{name:'Высота текущей работы, м',exact:true}).fill('120');
    await editor.getByRole('button',{name:'Фотосъёмка',exact:true}).click();
    check('altitude edits remain scoped to selected work',await editor.getByRole('spinbutton',{name:'Высота текущей работы, м',exact:true}).inputValue()==='100');
    await editor.getByRole('button',{name:'Тепловая съёмка',exact:true}).click();
    check('selected work retains its own altitude',await editor.getByRole('spinbutton',{name:'Высота текущей работы, м',exact:true}).inputValue()==='120');
    await editor.getByRole('button',{name:'Время',exact:true}).click();
    await editor.getByRole('checkbox',{name:'Свой период выполнения',exact:true}).check();
    check('per-work period is editable',await editor.getByRole('textbox',{name:'Начало периода работы',exact:true}).isEnabled());
    await editor.getByRole('button',{name:'Фотосъёмка',exact:true}).click();
    check('work period does not leak to another work',!await editor.getByRole('checkbox',{name:'Свой период выполнения',exact:true}).isChecked());
    await editor.getByRole('button',{name:'БВС',exact:true}).click();
    check('automatic assignment is explicit',await editor.getByRole('combobox',{name:'Назначение',exact:true}).inputValue()==='auto');
    await editor.getByRole('button',{name:'Участки',exact:true}).click();
    const before=await page.locator('.leaflet-container').evaluate(e=>e._leaflet_id);
    await editor.getByRole('button',{name:'Добавить участок',exact:true}).click();
    check('area cloning preserves map host',before===await page.locator('.leaflet-container').evaluate(e=>e._leaflet_id));
    await page.getByRole('button',{name:'Сохранить',exact:true}).click();
    await nav('Миссии').click();
    const home=page.getByRole('region',{name:'Список миссий',exact:true});
    check('saved and edited mission appears exactly once',await home.locator('.mb-record').count()===1);
    await home.getByRole('textbox',{name:'Поиск миссий',exact:true}).fill('does-not-exist');
    check('search filters list',await home.locator('.mb-record').count()===0);
    await home.getByRole('textbox',{name:'Поиск миссий',exact:true}).fill('QA');
    check('search finds edited mission',await home.locator('.mb-record').count()===1);
    await home.getByRole('textbox',{name:'Поиск миссий',exact:true}).fill('');
    await page.screenshot({path:`${out}/02-missions.png`});
    await nav('Выполнение').click();
    const queue=page.getByRole('region',{name:'Выбор миссии для выполнения'});
    await queue.getByRole('button',{name:'Подготовить пример: Съёмка участка',exact:true}).click();
    const preview=page.getByRole('dialog',{name:'Проверка перед загрузкой',exact:true});
    await preview.getByRole('button',{name:'Заменить текущую миссию',exact:true}).click();
    await page.getByRole('button',{name:'Расчёт вариантов',exact:true}).click();
    const response=page.waitForResponse(r=>r.url().endsWith('/api/planner/missions/solve')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();
    const solved=await(await response).json();
    check('real backend produces feasible candidate',solved.candidates[0].status==='feasible_model');
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    const approve=page.getByRole('dialog',{name:'Подтвердить модельный план',exact:true});
    check('safety acknowledgement is mandatory',await approve.getByRole('button',{name:'Подтвердить для симуляции',exact:true}).isDisabled());
    await approve.getByRole('checkbox').check();await approve.getByRole('button',{name:'Подтвердить для симуляции',exact:true}).click();
    await nav('Выполнение').click();
    const map=await page.locator('.mw-map-wrap').boundingBox(),panel=await page.locator('.mw-sidebar').boundingBox();
    check('execution map and controls share top row',Math.abs(map.y-panel.y)<4&&map.y<120&&map.height>500,JSON.stringify({map,panel}));
    await page.getByRole('combobox',{name:'Скорость симуляции',exact:true}).selectOption('300');
    await page.getByRole('button',{name:'Выполнить миссию',exact:true}).click();
    await page.waitForTimeout(1200);
    check('execution persists an actual model checkpoint',(await readRuns()).some(r=>r.status==='running'));
    await page.screenshot({path:`${out}/03-execution.png`});
    await page.getByRole('button',{name:'Пауза',exact:true}).click();
    await nav('Миссии').click();
    await home.getByRole('button',{name:/На паузе|Пауза/}).click();
    check('status filter shows selected execution',await home.locator('.mb-record').count()===1);
    await home.getByRole('button',{name:'Наблюдать',exact:true}).click();
    await page.getByRole('button',{name:'Продолжить выполнение',exact:true}).click();
    for(let i=0;i<250;i++){if((await readRuns()).some(r=>r.status==='completed'))break;await page.waitForTimeout(100);}
    check('mission reaches completed state',(await readRuns()).some(r=>r.status==='completed'));
    await nav('Миссии').click();
    await home.getByRole('button',{name:/^Завершены/}).click();
    await home.getByRole('button',{name:'Отчёт',exact:true}).click();
    check('results belong to selected mission',await page.getByRole('button',{name:'Отчёт о запуске JSON',exact:true}).isVisible());
    const report=JSON.parse(await save('run.report.json',()=>page.getByRole('button',{name:'Отчёт о запуске JSON',exact:true}).click()));
    check('export includes completed run, model-only journal and immutable evidence',report.operation.status==='completed'&&report.journal.modelOnly&&report.operation.integrityHash.length===64&&report.plannedArtifacts.kml.includes('<kml'));
    const html=await save('run.report.html',()=>page.getByRole('button',{name:'Отчёт HTML',exact:true}).click());
    check('standalone HTML report contains run identity and limits',html.includes(report.operation.id)&&html.includes('Реальные БВС не подключены'));
    await page.screenshot({path:`${out}/04-report.png`});
    await nav('Миссии').click();
    await page.setViewportSize({width:390,height:844});
    check('mobile missions do not overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`${out}/05-mobile.png`,fullPage:true});
    check('no browser exceptions',errors.length===0,errors.join('\n'));
  }catch(error){checks.push({name:'fatal',pass:false,detail:String(error)});await page.screenshot({path:`${out}/failure.png`,fullPage:true});}
  const report={at:new Date().toISOString(),checks,errors,status:checks.every(c=>c.pass)?'pass':'fail'};
  await save('browser-report.json',()=>page.evaluate(r=>{const a=document.createElement('a'),url=URL.createObjectURL(new Blob([JSON.stringify(r,null,2)],{type:'application/json'}));a.href=url;a.download='report.json';a.click();setTimeout(()=>URL.revokeObjectURL(url),1000);},report));
  return report;
}
