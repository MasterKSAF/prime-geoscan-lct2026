async (page) => {
  const out='output/playwright/release-obstacles', checks=[], errors=[];
  const check=(name,ok)=>{checks.push({name,pass:!!ok});if(!ok)throw Error(name);};
  const nav=name=>page.getByRole('tablist',{name:'Разделы стенда'}).getByRole('tab',{name,exact:true});
  const download=async(name,action)=>{const pending=page.waitForEvent('download');await action();const d=await pending;await d.saveAs(`${out}/${name}`);return d;};
  const load=async(file)=>{await nav('Редактор').click();await page.getByLabel('Файл миссии',{exact:true}).setInputFiles(file);await page.getByRole('dialog',{name:'Проверка перед загрузкой'}).getByRole('button',{name:'Заменить текущую миссию',exact:true}).click();};
  const solve=async(endpoint)=>{await page.getByRole('button',{name:'Расчёт вариантов',exact:true}).click();const pending=page.waitForResponse(r=>r.url().endsWith(endpoint)&&r.request().method()==='POST');await page.getByRole('button',{name:'Рассчитать варианты',exact:true}).click();const response=await pending;check('HTTP '+endpoint,response.status()===200);return response.json();};
  page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>void d.accept());
  try {
    await page.setViewportSize({width:1440,height:960});
    await nav('Парк БВС').click();
    const fleet=page.getByRole('region',{name:'Общий парк БВС',exact:true});
    const config=fleet.locator('details').filter({has:page.locator('summary',{hasText:'Добавить / импортировать БВС и изменить комплектации'})});
    if(await config.getAttribute('open')===null)await config.locator('summary').first().click();
    for(const model of ['Gemini','801','201'])check('catalog '+model,await fleet.getByRole('button',{name:`Добавить Геоскан ${model}`,exact:true}).isVisible());
    await page.screenshot({path:`${out}/fleet.png`});
    await load('public/planner/scenarios/demo-01-survey.mission.json');
    const result1=await solve('/api/planner/missions/solve');
    check('Demo 1 feasible',result1.candidates.some(c=>c.status==='feasible_model'));
    await load('public/planner/scenarios/demo-03-repair.mission.json');
    const result3=await solve('/api/planner/missions/solve');
    check('Demo 3 refuses unavailable resource',result3.candidates.every(c=>c.status!=='feasible_model'));
    await page.screenshot({path:`${out}/refusal.png`});
    await load('public/planner/scenarios/demo-02-expert-obstacles.mission.json');
    check('mission title present', (await page.getByRole('textbox',{name:'Название миссии',exact:true}).inputValue()).includes('Демо 2'));
    check('map visible after import',await page.locator('.leaflet-container').isVisible());
    await page.screenshot({path:`${out}/editor.png`});
    await page.getByRole('button',{name:'Сохранить',exact:true}).click();
    const result2=await solve('/api/planner/missions/solve-with-obstacles');
    check('full source remains attached',result2.document.obstacleLayer.sourceText.length>3000000);
    check('Demo 2 both criteria feasible',result2.candidates.length>=2&&result2.candidates.every(c=>c.status==='feasible_model'));
    check('Demo 2 checks no failures',result2.candidates.every(c=>!c.checks.some(x=>x.status==='fail')));
    check('uncertainty remains explicit',result2.candidates.some(c=>c.checks.some(x=>x.status==='unknown')));
    await page.screenshot({path:`${out}/calculated.png`});
    await page.getByRole('button',{name:'Проверить и подтвердить',exact:true}).click();
    const approve=page.getByRole('dialog',{name:'Подтвердить модельный план',exact:true});
    check('model acknowledgement required',await approve.getByRole('button',{name:'Подтвердить для симуляции',exact:true}).isDisabled());
    await approve.getByRole('checkbox').check();await approve.getByRole('button',{name:'Подтвердить для симуляции',exact:true}).click();
    await nav('Выполнение').click();
    await page.getByRole('combobox',{name:'Скорость симуляции',exact:true}).selectOption('300');
    await page.getByRole('button',{name:'Выполнить миссию',exact:true}).click();
    await page.getByRole('button',{name:'Пауза',exact:true}).waitFor();
    await page.screenshot({path:`${out}/execution.png`});
    check('map remains visible during run',await page.locator('.leaflet-container').isVisible());
    await page.getByRole('button',{name:'Пауза',exact:true}).waitFor({state:'hidden',timeout:30000});
    await nav('Миссии').click();
    const home=page.getByRole('region',{name:'Список миссий',exact:true});
    await home.getByRole('button',{name:/^Завершены/}).click();
    await page.screenshot({path:`${out}/missions.png`});
    await home.getByRole('button',{name:'Отчёт',exact:true}).click();
    check('report export available',await page.getByRole('button',{name:'Отчёт о запуске JSON',exact:true}).isVisible());
    await download('run.report.json',()=>page.getByRole('button',{name:'Отчёт о запуске JSON',exact:true}).click());
    await download('run.report.html',()=>page.getByRole('button',{name:'Отчёт HTML',exact:true}).click());
    await download('mission.evidence.zip',()=>page.getByRole('button',{name:/Скачать.*ZIP|ZIP.*доказательств|Архив.*ZIP/i}).click());
    await page.screenshot({path:`${out}/report.png`});
    await page.reload();await nav('Миссии').click();await home.getByRole('button',{name:/^Завершены/}).click();
    check('completed mission survives reload',await home.getByRole('button',{name:'Отчёт',exact:true}).isVisible());
    await page.setViewportSize({width:390,height:844});check('mobile list does not overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
    check('no page exceptions',errors.length===0);
  } catch(error) {checks.push({name:'fatal',pass:false,detail:String(error)});await page.screenshot({path:`${out}/failure.png`,fullPage:true});}
  const report={at:new Date().toISOString(),base:page.url(),checks,errors,status:checks.every(c=>c.pass)?'pass':'fail'};
  await download('browser-report.json',()=>page.evaluate(r=>{const a=document.createElement('a');a.href=URL.createObjectURL(new Blob([JSON.stringify(r,null,2)],{type:'application/json'}));a.download='browser-report.json';a.click();},report));
  return report;
}
