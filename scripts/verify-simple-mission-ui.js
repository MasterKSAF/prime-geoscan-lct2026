async (page) => {
  const out = 'output/playwright/simple-ui';
  const checks = [], errors = [];
  const check = (name, pass, detail = '') => {
    checks.push({ name, pass: !!pass, detail });
    if (!pass) throw Error(name + ': ' + detail);
  };
  const globalTab = (name) => page.getByRole('tablist', { name: 'Разделы стенда' }).getByRole('tab', { name, exact: true });
  const resultTab = (name) => page.getByRole('tablist', { name: 'Разделы результатов' }).getByRole('tab', { name, exact: true });
  const saveDownload = async (name, click) => {
    const promise = page.waitForEvent('download');
    await click();
    await (await promise).saveAs(`${out}/${name}`);
  };
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('dialog', (dialog) => void dialog.accept().catch(() => {}));
  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await globalTab('Миссии').click();
    const home = page.getByRole('region', { name: 'Задания и выполнения' });
    check('home has three list views, not six counters', await home.getByRole('tab').count() === 3 && !(await home.locator('.mo-stats').count()));
    await home.getByRole('tab', { name: /^В работе/ }).click();
    check('active list is selectable', await home.getByRole('tab', { name: /^В работе/ }).getAttribute('aria-selected') === 'true');
    await home.getByRole('tab', { name: /^История/ }).click();
    check('history is selectable', await home.getByRole('tab', { name: /^История/ }).getAttribute('aria-selected') === 'true');
    await home.getByRole('tab', { name: /^Задания/ }).click();
    await page.screenshot({ path: `${out}/missions.png` });
    await page.locator('input[type=file][accept=".json,.yaml,.yml"]').setInputFiles('public/planner/scenarios/automatic-tradeoff.mission.json');
    await page.getByRole('button', { name: 'Заменить текущее задание', exact: true }).click();
    check('editor has three primary sections', await page.locator('.mw-wizard-nav button').count() === 3);
    check('extra planning-step row removed', await page.locator('.mw-planning-steps').count() === 0);
    check('editor main bar has only Save Calculate and More', await page.locator('.mw-header-actions button:visible').count() === 3);
    const grid = await page.locator('.mw-grid').boundingBox(), map = await page.locator('.mw-map-wrap').boundingBox();
    check('editor gives map about 55 percent width', !!grid && !!map && map.width / grid.width > .50 && map.width / grid.width < .60);
    check('map is visible above viewport bottom', !!map && map.y < 180 && map.y + map.height <= 904);
    await page.getByRole('button', { name: 'Развернуть карту', exact: true }).click();
    check('expanded map keeps global navigation', await globalTab('Миссии').isVisible());
    check('expanded map hides only editing panels', !(await page.locator('.mw-sidebar').isVisible()) && await page.locator('.mw-map-wrap').isVisible());
    await page.getByRole('button', { name: 'Вернуть панели', exact: true }).click();
    check('editor panels restore', await page.locator('.mw-sidebar').isVisible());
    const editor = page.locator('.mw-simple-editor');
    await editor.getByRole('button', { name: 'Условия', exact: true }).click();
    check('conditions retain visible manual-weather provenance', (await page.locator('.mw-weather-summary').innerText()).includes('вручную'));
    check('conditions expose detailed safety settings on demand', (await editor.locator('summary').allTextContents()).some((text) => /резерв/i.test(text)));
    await editor.getByRole('button', { name: 'Парк', exact: true }).click();
    check('fleet editor collapsed, not deleted', await editor.getByText('Добавить БВС · Gemini, 801, 201 / изменить парк', { exact: true }).isVisible());
    await editor.getByText('Добавить БВС · Gemini, 801, 201 / изменить парк', { exact: true }).click();
    check('full fleet fields are still reachable', await editor.locator('input:visible').count() > 3);
    await editor.getByRole('button', { name: 'Задание', exact: true }).click();
    await editor.getByRole('button', { name: 'Территория', exact: true }).click();
    check('territory editor and coordinates remain reachable', await page.getByRole('status', { name: 'Координаты карты WGS84' }).isVisible());
    await editor.getByRole('button', { name: 'Работы', exact: true }).click();
    await page.screenshot({ path: `${out}/editor.png` });
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await globalTab('Миссии').click();
    await home.getByRole('tab', { name: /^Задания/ }).click();
    await home.getByRole('button', { name: 'Открыть задание', exact: true }).first().waitFor();
    check('saved task remains in task list, not queued automatically', await home.getByRole('button', { name: 'Открыть задание', exact: true }).count() === 1 && (await home.getByRole('tab', { name: /^В работе/ }).innerText()).includes('0'));
    await home.getByRole('button', { name: 'Открыть задание', exact: true }).first().click();
    await page.getByRole('button', { name: 'Заменить текущее задание', exact: true }).click();
    const pending = page.waitForResponse((r) => r.url().endsWith('/api/planner/missions/solve') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Рассчитать варианты', exact: true }).click();
    const result = await (await pending).json();
    check('saved mission calculates full feasible plan', result.candidates[0].status === 'feasible_model');
    check('variants retain safety summary', await page.locator('.mw-inspector .ms-safety-summary').isVisible());
    await globalTab('Результаты').click();
    check('results default to Summary', await resultTab('Итог').getAttribute('aria-selected') === 'true');
    const tabContrast = await page.locator('.mw-result-tabs [role="tab"]').evaluateAll((tabs) => {
      const luminance = (color) => {
        const channels = color.match(/[\d.]+/g).slice(0, 3).map(Number).map((channel) => {
          const value = channel / 255;
          return value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4;
        });
        return channels[0] * .2126 + channels[1] * .7152 + channels[2] * .0722;
      };
      return tabs.map((tab) => {
        const style = getComputedStyle(tab);
        const a = luminance(style.color), b = luminance(style.backgroundColor);
        return { label: tab.textContent, ratio: (Math.max(a, b) + .05) / (Math.min(a, b) + .05) };
      });
    });
    check('result tab labels meet 4.5 contrast in light theme', tabContrast.length === 3 && tabContrast.every((tab) => tab.ratio >= 4.5), JSON.stringify(tabContrast));
    check('analysis is not loaded into Summary', await page.getByRole('region', { name: 'Анализ решения' }).count() === 0);
    check('format buttons are hidden from Summary', !(await page.getByRole('button', { name: 'KML', exact: true }).isVisible()));
    check('summary shows technical checks with unknowns', await page.locator('.mw-result-summary .ms-safety-chip').count() >= 5 && (await page.locator('.mw-result-summary .ms-safety-counts').innerText()).includes('Не подтверждено: 5'));
    check('source-area coverage is labelled explicitly', await page.getByText('Покрытие исходной площади', { exact: true }).isVisible());
    await page.screenshot({ path: `${out}/summary.png`, fullPage: true });
    await saveDownload('mission.evidence.json', () => page.getByRole('button', { name: 'Скачать комплект JSON', exact: true }).click());
    await page.locator('.mw-result-summary').getByRole('button', { name: 'Все проверки', exact: true }).click();
    check('All checks opens Analysis and expands actual checks', await resultTab('Анализ').getAttribute('aria-selected') === 'true' && await page.locator('#result-panel-analysis > details[open] .mw-check').count() === result.candidates[0].checks.length);
    check('deep analysis remains reachable', await page.getByRole('region', { name: 'Анализ решения' }).isVisible());
    await resultTab('Файлы').click();
    check('all export formats moved to Files', await page.getByRole('button', { name: 'KML', exact: true }).isVisible() && await page.getByRole('button', { name: 'Описание MD', exact: true }).isVisible());
    check('evidence hash remains accessible', (await page.locator('.mw-delivery').innerText()).includes(result.inputHash));
    await page.screenshot({ path: `${out}/files.png`, fullPage: true });
    await globalTab('Редактор').click();
    await page.getByRole('button', { name: 'Проверить и подтвердить', exact: true }).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await page.getByRole('dialog').getByRole('button', { name: /Подтвердить/ }).click();
    await page.getByRole('button', { name: 'К выполнению', exact: true }).click();
    check('flight instruments are initially hidden', !(await page.getByRole('region', { name: 'Состояние выбранного БВС' }).count()));
    await page.getByRole('button', {name:'Пояснение: Выполнение симуляции',exact:true}).hover();
    check('playback explains simulation on demand and retains speed control', (await page.getByRole('tooltip').filter({visible:true}).innerText()).includes('Аппараты не подключены') && await page.getByRole('combobox', { name: 'Скорость симуляции' }).isVisible());
    await page.keyboard.press('Escape');
    check('queue action is removed from playback', await page.locator('.mw-playback').getByRole('button', { name: 'Поставить в план', exact: true }).count() === 0);
    await page.getByRole('button', { name: 'Выбрать Свой профиль БВС · 01', exact: true }).click();
    check('vehicle click reveals instruments', await page.getByRole('region', { name: 'Состояние выбранного БВС' }).isVisible());
    await page.getByRole('button', { name: 'Скрыть показатели БВС', exact: true }).click();
    await page.getByRole('button', { name: 'Начать симуляцию', exact: true }).click();
    await page.waitForFunction(() => Number(document.querySelector('input[aria-label="Время симуляции"]')?.value) > 4);
    check('simulation advances in simplified layout', await page.getByRole('button', { name: 'Пауза', exact: true }).isVisible());
    await page.screenshot({ path: `${out}/execution.png` });
    await page.getByRole('button', { name: 'Пауза', exact: true }).click();
    await page.getByRole('button', { name: 'Журнал', exact: true }).click();
    check('journal available without scrolling below map', await page.getByRole('dialog', { name: 'Журнал миссии',exact:true }).isVisible());
    await page.getByRole('dialog').getByRole('button', { name: 'Закрыть окно' }).click();
    await page.getByRole('button', { name: 'Действия с этой миссией', exact: true }).click();
    check('secondary mission actions remain available', await page.getByRole('dialog').getByRole('button', { name: 'Состояние парка', exact: true }).isVisible() && await page.getByRole('dialog').getByRole('button', { name: 'Создать пересмотр задания', exact: true }).isVisible());
    await page.getByRole('dialog').getByRole('button', { name: 'Закрыть окно' }).click();
    await globalTab('Миссии').click();
    await home.getByRole('tab', { name: /^В работе/ }).click();
    check('paused run remains in Active list', await home.locator('.mo-run:visible').count() === 1);
    await home.getByRole('tab', { name: /^История/ }).click();
    check('active run never appears as finished history', await home.locator('.mo-run:visible').count() === 0);
    await globalTab('Результаты').click();
    await page.setViewportSize({ width: 390, height: 844 });
    check('mobile Summary has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    check('mobile navigation remains visible', await globalTab('Миссии').isVisible());
    await page.screenshot({ path: `${out}/mobile.png`, fullPage: true });
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByRole('button', { name: 'Настройки и справка', exact: true }).click();
    await page.getByRole('button', { name: 'Справка по программе', exact: true }).click();
    check('in-app help records the relocation map', await page.getByRole('dialog').getByText('Что где находится', { exact: true }).isVisible());
    await page.getByRole('dialog').getByRole('button', { name: 'Закрыть окно' }).click();
    check('no unhandled browser errors', errors.length === 0, errors.join('\n'));
  } catch (error) {
    checks.push({ name: 'fatal', pass: false, detail: String(error) });
    await page.screenshot({ path: `${out}/failure.png`, fullPage: true });
  }
  const report = { at: new Date().toISOString(), checks, errors };
  await saveDownload('browser-report.json', () => page.evaluate((value) => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(value, null, 2)], { type: 'application/json' }));
    const a = document.createElement('a'); a.href = url; a.download = 'browser-report.json'; a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }, report));
  return report;
}
